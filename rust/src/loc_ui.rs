pub fn ui() -> &'static Ui {
    match current() {
        Lang::En => &EN,
        Lang::Fr => &FR,
        Lang::Es => &ES,
        Lang::Ru => &RU,
        Lang::De => &DE,
        Lang::It => &IT,
        Lang::Pt => &PT,
        Lang::Zh => &ZH,
        Lang::Tr => &TR,
    }
}

/// "94 jeux", "3 633 jeux": each language's own plural rule (a count-style
/// phrasing in Russian and Chinese), and the number with the importer's
/// thousands separator (`imp_count`), so an archive's page writes its count
/// the way the row that opened it does ("6 / 3 633").
pub fn games(n: usize) -> std::string::String {
    let c = crate::backend::render::imp_count(n as u64);
    match current() {
        Lang::En if n == 1 => "1 game".into(),
        Lang::En => std::format!("{} games", c),
        Lang::Fr if n <= 1 => std::format!("{} jeu", c),
        Lang::Fr => std::format!("{} jeux", c),
        Lang::Es if n == 1 => "1 juego".into(),
        Lang::Es => std::format!("{} juegos", c),
        Lang::Ru => std::format!("Игр: {}", c),
        Lang::De if n == 1 => "1 Spiel".into(),
        Lang::De => std::format!("{} Spiele", c),
        Lang::It if n == 1 => "1 gioco".into(),
        Lang::It => std::format!("{} giochi", c),
        Lang::Pt if n == 1 => "1 jogo".into(),
        Lang::Pt => std::format!("{} jogos", c),
        Lang::Zh => std::format!("游戏：{}", c),
        Lang::Tr => std::format!("{} oyun", c),
    }
}

/// `n` percent, the way the language writes it ("150 %", "150%", "%150"):
/// the zoom's rows and the framing's header, an import's progress. A format
/// string wrote "150 %" in Turkish and Chinese too, under a framing legend that
/// said "%100" and "100%".
pub fn percent(n: u32) -> std::string::String {
    ui().percent.replacen("{}", &n.to_string(), 1)
}

/// The layout's name, for the home header.
pub fn view_label(v: u8) -> &'static str {
    let u = ui();
    match v % 4 {
        1 => u.view_list,
        2 => u.view_strip,
        3 => u.view_shelf,
        _ => u.view_grid,
    }
}

/// Time played, written the way each language says it: "2 h 39 de jeu",
/// "2 h 39 played". Under an hour the hours are left out rather than shown as
/// "0 h".
pub fn playtime(secs: u64) -> std::string::String {
    let h = secs / 3600;
    let m = (secs % 3600) / 60;
    match current() {
        Lang::En if h == 0 => std::format!("{} min played", m),
        Lang::En => std::format!("{} h {:02} played", h, m),
        Lang::Fr if h == 0 => std::format!("{} min de jeu", m),
        Lang::Fr => std::format!("{} h {:02} de jeu", h, m),
        Lang::Es if h == 0 => std::format!("{} min jugados", m),
        Lang::Es => std::format!("{} h {:02} jugadas", h, m),
        Lang::Ru if h == 0 => std::format!("{} мин в игре", m),
        Lang::Ru => std::format!("{} ч {:02} мин в игре", h, m),
        Lang::De if h == 0 => std::format!("{} Min. gespielt", m),
        Lang::De => std::format!("{} Std. {:02} gespielt", h, m),
        Lang::It if h == 0 => std::format!("{} min di gioco", m),
        Lang::It => std::format!("{} h {:02} di gioco", h, m),
        Lang::Pt if h == 0 => std::format!("{} min jogados", m),
        Lang::Pt => std::format!("{} h {:02} jogadas", h, m),
        Lang::Zh if h == 0 => std::format!("已玩 {} 分钟", m),
        Lang::Zh => std::format!("已玩 {} 小时 {} 分钟", h, m),
        Lang::Tr if h == 0 => std::format!("{} dk oynandı", m),
        Lang::Tr => std::format!("{} sa {:02} dk oynandı", h, m),
    }
}
